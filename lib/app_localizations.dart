  static List<Locale> get supportedLocales =>
      supportedLanguages.map((lang) => Locale(lang.code)).toList();

  static AppLanguage getLanguage(String code) {
    return supportedLanguages.firstWhere(
      (lang) => lang.code == code,
      orElse: () => const AppLanguage(
        code: 'en',
        nativeName: 'English',
        englishName: 'English',
      ),
    );
  }

  static String getNativeName(String code) => getLanguage(code).nativeName;
  static String getEnglishName(String code) => getLanguage(code).englishName;

  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(context, AppLocalizations)!;
  }

  static String translate(BuildContext context, String key) {
    try {
      final locale = Localizations.localeOf(context);
      final map = _translations[locale.languageCode] ?? _translations['en']!;
      return map[key] ?? _translations['en']?[key] ?? key;
    } catch (_) {
      return _translations['en']?[key] ?? key;
    }
  }

  static String translateWithCode(String languageCode, String key) {
    final map = _translations[languageCode] ?? _translations['en']!;
    return map[key] ?? _translations['en']?[key] ?? key;
  }

